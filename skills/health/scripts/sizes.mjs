import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { SKIP_DIRS } from './stacks.mjs';

/* Lists hand-written files over the doctrine's size limits.

     node sizes.mjs [dir] [--react <dir>]…

   A code line is neither blank nor comment-only. Limits: 400 source, 600
   tests, 200 React components (.tsx/.jsx under a --react dir), 800 with a
   valid waiver. Generated files, data-only files and minified bundles are not
   sized. Exits 1 when anything is over. */
const LIMITS = { source: 400, test: 600, component: 200, ceiling: 800 };
const JS = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.mts', '.cts', '.vue', '.svelte']);
const PY = new Set(['.py']);
const TEST = /(\.(test|spec)\.[cm]?[jt]sx?$)|((^|\/)test_[^/]+\.py$)|(_test\.py$)|((^|\/)(e2e|tests?|__tests__)\/)/;
const GENERATED = /@generated|generated by|auto-generated|do not edit/i;
const WAIVER = /doctrine-allow size:\s*(D1|D2|D3|E)\s*-\s*(.+)/;
const STRINGS = /'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`[^`]*`/g;
const JS_LOGIC = /\b(function|class|if|for|while|return|switch)\b|=>/;
const PY_LOGIC = /^\s*(def|class|if|for|while|return)\b|\blambda\b/m;

const opensTriple = (line, quote) => line.split(quote).length % 2 === 0;

export function codeLines(text, ext) {
  const py = PY.has(ext);
  let count = 0;
  let block = null; // inside a comment or docstring: lines not counted
  let string = null; // inside a multi-line string that is a value: lines counted
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (block) {
      if (line.includes(block)) block = null;
      continue;
    }
    if (string) {
      count += 1;
      if (line.includes(string)) string = null;
      continue;
    }
    if (!line) continue;
    if (py) {
      if (line.startsWith('#')) continue;
      const quote = line.startsWith('"""') ? '"""' : line.startsWith("'''") ? "'''" : null;
      if (quote) {
        // A string that starts a line is a docstring; it runs to its closing quotes.
        if (opensTriple(line, quote)) block = quote;
        continue;
      }
      // A triple-quoted string opened mid-line is a value, and its lines are code.
      string = ['"""', "'''"].find((q) => opensTriple(line, q)) ?? null;
    } else {
      if (line.startsWith('//') || line.startsWith('*')) continue;
      if (line.startsWith('/*')) {
        if (!line.includes('*/')) block = '*/';
        continue;
      }
    }
    count += 1;
  }
  return count;
}

const isDataOnly = (text, ext) => {
  const bare = text.replace(STRINGS, '""').replace(/\/\*[\s\S]*?\*\/|\/\/.*$|#.*$/gm, '');
  return !(PY.has(ext) ? PY_LOGIC : JS_LOGIC).test(bare);
};

/* In a git repository the files are what git tracks or would track, so build
   output and anything else the project ignores is never sized. */
const listFiles = (root) => {
  try {
    const out = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 });
    // A tracked file deleted from disk is still listed until the deletion is committed.
    const files = out.split('\0').filter((f) => f && (JS.has(extname(f)) || PY.has(extname(f))) && existsSync(join(root, f)));
    if (!files.length) return walk(root);
    return files.map((f) => join(root, f));
  } catch {
    return walk(root);
  }
};

const walk = (dir, out = []) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name) && !entry.name.startsWith('.')) walk(join(dir, entry.name), out);
    } else if (JS.has(extname(entry.name)) || PY.has(extname(entry.name))) out.push(join(dir, entry.name));
  }
  return out;
};

export function oversized(root, reactDirs = []) {
  const over = [];
  for (const abs of listFiles(root)) {
    const rel = relative(root, abs).split(sep).join('/');
    const ext = extname(abs);
    if (rel.endsWith('.min.js')) continue;
    const text = readFileSync(abs, 'utf8').replaceAll('\r', '');
    const head = text.split('\n').slice(0, 10);
    if (head.slice(0, 5).some((l) => GENERATED.test(l)) || isDataOnly(text, ext)) continue;
    const lines = codeLines(text, ext);
    const isTest = TEST.test(rel);
    const isComponent = !isTest && /\.[jt]sx$/.test(rel) && reactDirs.some((d) => abs.startsWith(d + sep));
    const limit = isTest ? LIMITS.test : isComponent ? LIMITS.component : LIMITS.source;
    if (lines <= limit) continue;
    const waiver = head.map((l) => WAIVER.exec(l)).find(Boolean);
    if (waiver && !isComponent && lines <= LIMITS.ceiling && (waiver[1] !== 'E' || /bench/i.test(waiver[2]))) continue;
    let note = '';
    if (waiver && isComponent) note = 'components take no waiver';
    else if (waiver && lines > LIMITS.ceiling) note = `waived, but over the ${LIMITS.ceiling} ceiling`;
    else if (waiver) note = 'E waiver must name its benchmark';
    over.push({ rel, lines, limit, note });
  }
  return over.sort((a, b) => b.lines - a.lines);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  const reactDirs = args.flatMap((a, i) => (args[i - 1] === '--react' ? [a] : []));
  const root = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--react') ?? '.';
  const over = oversized(root, reactDirs);
  for (const f of over) console.log(`${String(f.lines).padStart(6)} / ${f.limit}  ${f.rel}${f.note ? `  (${f.note})` : ''}`);
  console.log(over.length ? `\n${over.length} file(s) over their limit` : 'every file within its limit');
  process.exit(over.length ? 1 : 0);
}
